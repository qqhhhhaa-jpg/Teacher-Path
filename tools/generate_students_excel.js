// Pseudorandom grade generator with realistic curve (mostly passing with top performers and few repeats)
function getRealisticGrade(seed, type) {
  const base = 50 + ((seed * 17) % 46); // 50 to 95
  if (type === 'act') return 8 + ((seed * 7) % 3); // 8, 9, 10
  if (seed % 11 === 0) return 40 + (seed % 10); // few fails around 40-49
  return Math.min(100, Math.max(35, base));
}

